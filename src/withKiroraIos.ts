import fs from 'fs';
import path from 'path';
import {
  type ConfigPlugin,
  IOSConfig,
  withDangerousMod,
  withEntitlementsPlist,
  withInfoPlist,
  withPodfile,
  withXcodeProject,
  type XcodeProject
} from 'expo/config-plugins';
import type { ExpoConfig } from 'expo/config';
import { type KiroraPluginProps, NSE_TARGET_NAME } from './types';
import { fail } from './validate';

const SWIFT_FILE = 'NotificationService.swift';
const INFO_PLIST = `${NSE_TARGET_NAME}-Info.plist`;
const ENTITLEMENTS = `${NSE_TARGET_NAME}.entitlements`;

// Marks the plugin's Podfile edits, so a second prebuild replaces them instead of adding more.
const PODFILE_BEGIN = '# @kirora/expo-plugin begin';
const PODFILE_END = '# @kirora/expo-plugin end';

const withApsEnvironment: ConfigPlugin<KiroraPluginProps> = (config, props) =>
  withEntitlementsPlist(config, (config) => {
    config.modResults['aps-environment'] = props.mode ?? 'development';
    return config;
  });

/**
 * The hosts of the app's own universal links (`applinks:` in `ios.associatedDomains` or the
 * associated-domains entitlement), without a `?mode=` suffix: `example.com`, `*.example.com`.
 */
function universalLinkHosts(config: ExpoConfig): string[] {
  const domains = [
    ...(config.ios?.associatedDomains ?? []),
    ...((config.ios?.entitlements?.['com.apple.developer.associated-domains'] as string[] | undefined) ?? [])
  ];
  return domains.filter((d) => d.startsWith('applinks:')).map((d) => d.slice('applinks:'.length).split('?')[0]);
}

/**
 * Lists the app's universal-link hosts in `KiroraUniversalLinkHosts`, which the Kirora iOS SDK
 * reads: a push's https link to one of them opens in the app, any other in Safari. Hosts the app
 * lists there itself (`ios.infoPlist`) are kept.
 */
const withUniversalLinkHosts: ConfigPlugin = (config) =>
  withInfoPlist(config, (config) => {
    const listed = (config.modResults.KiroraUniversalLinkHosts as string[] | undefined) ?? [];
    const hosts = [...new Set([...listed, ...universalLinkHosts(config)])];
    if (hosts.length > 0) config.modResults.KiroraUniversalLinkHosts = hosts;
    return config;
  });

function escapeXml(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function infoPlist(config: ExpoConfig, props: KiroraPluginProps): string {
  const apiUrl = props.ios?.apiUrl
    ? `\n\t<key>KiroraApiUrl</key>\n\t<string>${escapeXml(props.ios.apiUrl)}</string>`
    : '';
  // The versions must match the app's, or App Store Connect warns about the extension.
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
\t<key>CFBundleDevelopmentRegion</key>
\t<string>$(DEVELOPMENT_LANGUAGE)</string>
\t<key>CFBundleDisplayName</key>
\t<string>${NSE_TARGET_NAME}</string>
\t<key>CFBundleExecutable</key>
\t<string>$(EXECUTABLE_NAME)</string>
\t<key>CFBundleIdentifier</key>
\t<string>$(PRODUCT_BUNDLE_IDENTIFIER)</string>
\t<key>CFBundleInfoDictionaryVersion</key>
\t<string>6.0</string>
\t<key>CFBundleName</key>
\t<string>$(PRODUCT_NAME)</string>
\t<key>CFBundlePackageType</key>
\t<string>$(PRODUCT_BUNDLE_PACKAGE_TYPE)</string>
\t<key>CFBundleShortVersionString</key>
\t<string>${escapeXml(IOSConfig.Version.getVersion(config))}</string>
\t<key>CFBundleVersion</key>
\t<string>${escapeXml(IOSConfig.Version.getBuildNumber(config))}</string>${apiUrl}
\t<key>NSExtension</key>
\t<dict>
\t\t<key>NSExtensionPointIdentifier</key>
\t\t<string>com.apple.usernotifications.service</string>
\t\t<key>NSExtensionPrincipalClass</key>
\t\t<string>$(PRODUCT_MODULE_NAME).NotificationService</string>
\t</dict>
</dict>
</plist>
`;
}

// Kirora's extension needs no App Group or other capability, so its entitlements are empty.
const EMPTY_ENTITLEMENTS = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict/>
</plist>
`;

/** The extension's own Swift module: anything but the pod's module name. */
const NSE_MODULE_NAME = 'KiroraNotificationServiceApp';

const SWIFT_SOURCE = `// Generated by @kirora/expo-plugin on prebuild; edits here are overwritten.
import KiroraNotificationService

final class NotificationService: KiroraNotificationServiceExtension {}
`;

const withExtensionFiles: ConfigPlugin<KiroraPluginProps> = (config, props) =>
  withDangerousMod(config, [
    'ios',
    async (config) => {
      const dir = path.join(config.modRequest.platformProjectRoot, NSE_TARGET_NAME);
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, SWIFT_FILE), SWIFT_SOURCE);
      fs.writeFileSync(path.join(dir, INFO_PLIST), infoPlist(config, props));
      fs.writeFileSync(path.join(dir, ENTITLEMENTS), EMPTY_ENTITLEMENTS);
      return config;
    }
  ]);

const { getNativeTargets } = IOSConfig.Target;
const { getBuildConfigurationsForListId, unquote } = IOSConfig.XcodeUtils;

// Expo's own minimum.
const DEFAULT_IOS_DEPLOYMENT_TARGET = '15.1';

/** Whether the extension is on: the default, unless the option is false. */
function nseEnabled(props: KiroraPluginProps): boolean {
  return props.ios?.notificationServiceExtension !== false;
}

function extensionBundleId(config: ExpoConfig): string {
  return `${config.ios?.bundleIdentifier}.${NSE_TARGET_NAME}`;
}

/**
 * The extension's deployment target. The plugin also makes it the extension's Podfile platform,
 * so its pods are always built for the same target.
 */
function extensionDeploymentTarget(config: ExpoConfig, props: KiroraPluginProps): string {
  return (
    props.ios?.deploymentTarget ?? IOSConfig.DeploymentTarget.getDeploymentTarget(config) ?? DEFAULT_IOS_DEPLOYMENT_TARGET
  );
}

/** Adds the extension's files group and target, the app's dependency on it and its embedding. */
function addExtensionTarget(project: XcodeProject, bundleId: string): string {
  const group = project.addPbxGroup([SWIFT_FILE, INFO_PLIST, ENTITLEMENTS], NSE_TARGET_NAME, NSE_TARGET_NAME);
  // Show the extension's folder at the top of Xcode's navigator, in the project's main group.
  project.addToPbxGroup(group.uuid, project.getFirstProject().firstProject.mainGroup);

  // The xcode library's addTarget expects these sections, which a one-target project lacks.
  const objects = project.hash.project.objects;
  objects.PBXTargetDependency = objects.PBXTargetDependency ?? {};
  objects.PBXContainerItemProxy = objects.PBXContainerItemProxy ?? {};

  const target = project.addTarget(NSE_TARGET_NAME, 'app_extension', NSE_TARGET_NAME, bundleId);
  project.addBuildPhase([SWIFT_FILE], 'PBXSourcesBuildPhase', 'Sources', target.uuid);
  project.addBuildPhase([], 'PBXResourcesBuildPhase', 'Resources', target.uuid);
  project.addBuildPhase([], 'PBXFrameworksBuildPhase', 'Frameworks', target.uuid);
  return target.uuid;
}

const withExtensionTarget: ConfigPlugin<KiroraPluginProps> = (config, props) =>
  withXcodeProject(config, (config) => {
    const project = config.modResults;
    // By unquoted name: the xcode library's own pbxTargetByName misses the quoted name it
    // writes, so a second prebuild would add a second target.
    const existing = getNativeTargets(project).find(([, target]) => unquote(target.name) === NSE_TARGET_NAME)?.[0];

    if (!nseEnabled(props)) {
      if (existing) {
        fail(
          `ios.notificationServiceExtension is false but ios/ still has the ${NSE_TARGET_NAME} target ` +
            'from an earlier prebuild. Run `npx expo prebuild --clean`.'
        );
      }
      return config;
    }

    if (!config.ios?.bundleIdentifier) fail("set ios.bundleIdentifier; the extension's identifier derives from it");
    const bundleId = extensionBundleId(config);
    const team = props.ios?.appleTeamId ?? config.ios?.appleTeamId;
    const deploymentTarget = extensionDeploymentTarget(config, props);
    const uuid = existing ?? addExtensionTarget(project, bundleId);
    const target = project.pbxNativeTargetSection()[uuid];

    // Applied on every prebuild, so changed options reach an existing target too.
    for (const [, buildConfig] of getBuildConfigurationsForListId(project, target.buildConfigurationList)) {
      const settings = buildConfig.buildSettings;
      settings.PRODUCT_BUNDLE_IDENTIFIER = `"${bundleId}"`;
      settings.IPHONEOS_DEPLOYMENT_TARGET = deploymentTarget;
      settings.TARGETED_DEVICE_FAMILY = '"1,2"';
      settings.SWIFT_VERSION = '5.0';
      // The target shares its name with the KiroraNotificationService pod. Left as the target name,
      // its own Swift module would shadow the pod's, and `import KiroraNotificationService` would
      // find no KiroraNotificationServiceExtension. Info.plist names the class through this.
      settings.PRODUCT_MODULE_NAME = NSE_MODULE_NAME;
      settings.CODE_SIGN_ENTITLEMENTS = `${NSE_TARGET_NAME}/${ENTITLEMENTS}`;
      settings.CODE_SIGN_STYLE = 'Automatic';
      IOSConfig.DevelopmentTeam.setDevelopmentTeamForBuildConfiguration(buildConfig, team);
    }
    if (team) project.addTargetAttribute('DevelopmentTeam', team, { uuid });
    return config;
  });

/**
 * The kirora-ios copy @kirora/react-native bundles (CocoaPods trunk has no Kirora), relative to
 * the Podfile, so the extension's pod is the version the app's SDK is.
 */
function bundledIosSdk({ projectRoot, platformProjectRoot }: { projectRoot: string; platformProjectRoot: string }): string {
  let manifest: string;
  try {
    manifest = require.resolve('@kirora/react-native/package.json', { paths: [projectRoot] });
  } catch {
    fail('the Notification Service Extension needs @kirora/react-native installed');
  }
  const sdk = path.join(path.dirname(manifest), 'ios', 'vendor', 'kirora-ios');
  // require.resolve gives a real path (macOS's /var is /private/var): compare it with one.
  const podfileDir = path.join(fs.realpathSync(projectRoot), path.relative(projectRoot, platformProjectRoot));
  return path.relative(podfileDir, sdk).split(path.sep).join('/');
}

function rubyString(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

/** The Podfile with the plugin's earlier edits removed. */
function withoutOurEdits(podfile: string): string {
  const block = new RegExp(`\\n?[ \\t]*${PODFILE_BEGIN}[\\s\\S]*?${PODFILE_END}\\n?`, 'g');
  return podfile.replace(block, '\n');
}

const withKiroraPodfile: ConfigPlugin<KiroraPluginProps> = (config, props) =>
  withPodfile(config, (config) => {
    let podfile = withoutOurEdits(config.modResults.contents);
    if (nseEnabled(props)) {
      const pod = `pod 'KiroraNotificationService', :path => ${rubyString(bundledIosSdk(config.modRequest))}`;
      // A sibling of the app's target, so it gets none of the app's pods. Its platform is the
      // extension's deployment target, and its framework linkage the app's (the same lines as
      // Expo's template): CocoaPods rejects an extension whose linkage differs from the app's.
      const lines = [
        PODFILE_BEGIN,
        `target '${NSE_TARGET_NAME}' do`,
        `  platform :ios, ${rubyString(extensionDeploymentTarget(config, props))}`,
        "  use_frameworks! :linkage => podfile_properties['ios.useFrameworks'].to_sym if defined?(podfile_properties) && podfile_properties['ios.useFrameworks']",
        "  use_frameworks! :linkage => ENV['USE_FRAMEWORKS'].to_sym if ENV['USE_FRAMEWORKS']",
        `  ${pod}`,
        'end',
        PODFILE_END
      ];
      podfile = `${podfile.trimEnd()}\n\n${lines.join('\n')}\n`;
    }
    config.modResults.contents = podfile;
    return config;
  });

/** Tells EAS Build to create and sign the extension's bundle identifier with the app's. */
function withEasAppExtension(config: ExpoConfig): ExpoConfig {
  const ios = ((((config.extra ??= {}).eas ??= {}).build ??= {}).experimental ??= {}).ios ??= {};
  ios.appExtensions = [
    ...(ios.appExtensions ?? []).filter((e: { targetName: string }) => e.targetName !== NSE_TARGET_NAME),
    { targetName: NSE_TARGET_NAME, bundleIdentifier: extensionBundleId(config), entitlements: {} }
  ];
  return config;
}

export const withKiroraIos: ConfigPlugin<KiroraPluginProps> = (config, props) => {
  config = withApsEnvironment(config, props);
  config = withUniversalLinkHosts(config);
  const nse = nseEnabled(props);
  if (nse) config = withExtensionFiles(config, props);
  // Always registered: it also catches an extension left over from before the option was false.
  // It checks ios.bundleIdentifier itself, inside the iOS mod, so Android-only apps don't need one.
  config = withExtensionTarget(config, props);
  if (nse && config.ios?.bundleIdentifier) config = withEasAppExtension(config);
  return withKiroraPodfile(config, props);
};
